const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const templates = Object.entries(english).filter(([key]) => /\{\d+\}/.test(key)).sort((a,b) => b[0].length-a[0].length).map(([key, value]) => ({
  key, pattern: new RegExp("^" + key.split(/\{\d+\}/).map(escape).join("(.+?)") + "$"), value,
}));
export function createTranslator(language: Language) {
  function translate<T>(input: T): T {
    if (typeof input !== "string") return input;
    const text = input.trim();
    const dictionary = language === "en" ? english : thai;
    let result = dictionary[text];
    if (result === undefined && language === "en") {
      for (const { key, pattern, value } of templates) {
        const match = text.match(pattern);
        if (match) {
          result = value.replace(/\{(\d+)\}/g, (_, index) => {
            const captured = match[Number(index) + 1];
            return key.startsWith("โซน ") ? (english[captured] ?? captured) : captured;
          });
          break;
        }
      }
      if (result === undefined && text.includes(" • ")) result = text.split(" • ").map(part => translate(part)).join(" • ");
    }
    if (result === undefined) return input;
    return (input.slice(0, input.indexOf(text)) + result + input.slice(input.indexOf(text) + text.length)) as T;
  }
  return translate;
}
